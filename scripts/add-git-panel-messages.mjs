const path = "lib/i18n/locale-plugins.ts";
const source = readFileSync(path, "utf8");

function block(messages) {
  return Object.entries(messages)
    .map(([key, value]) => `      "${key}": ${JSON.stringify(value)},`)
    .join("\n");
}

// Each locale block's last gitPanel key is the anchor; the panel's keys follow it.
const ANCHORS = {
  en: '"gitPanel.showAllFiles": "Show all files",',
  "zh-CN": '"gitPanel.showAllFiles": "显示全部文件",',
  "zh-TW": '"gitPanel.showAllFiles": "顯示全部檔案",',
};

let out = source;
const report = [];
for (const [locale, anchor] of Object.entries(ANCHORS)) {
  const messages = locale === "en" ? EN : locale === "zh-CN" ? ZH_CN : ZH_TW;
  const index = out.indexOf(anchor);
  if (index < 0) {
    report.push(`${locale}: anchor not found`);
    continue;
  }
  const insertAt = index + anchor.length;
  out = `${out.slice(0, insertAt)}\n${block(messages)}${out.slice(insertAt)}`;
  report.push(`${locale}: +${Object.keys(messages).length} keys`);
}

writeFileSync(path, out);

const keys = new Set([...Object.keys(EN), ...Object.keys(ZH_CN), ...Object.keys(ZH_TW)]);
const missing = [];
for (const [locale, messages] of [["en", EN], ["zh-CN", ZH_CN], ["zh-TW", ZH_TW]]) {
  for (const key of keys) if (!(key in messages)) missing.push(`${locale}: ${key}`);
}
console.log(report.join("\n"));
if (missing.length) console.log(`MISSING\n${missing.join("\n")}`);
